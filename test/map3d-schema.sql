CREATE TABLE meta(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE assets(key TEXT PRIMARY KEY,path TEXT NOT NULL,offset INTEGER NOT NULL,bytes INTEGER NOT NULL,sha256 TEXT NOT NULL,mime TEXT NOT NULL,encoding TEXT NOT NULL DEFAULT '',cache TEXT NOT NULL);
CREATE TABLE instances(slug TEXT PRIMARY KEY,status TEXT NOT NULL,chunks TEXT NOT NULL);
CREATE TABLE definitions(slug TEXT NOT NULL,id TEXT NOT NULL,metadata TEXT NOT NULL,ambiguous INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(slug,id));
CREATE TABLE documents(id INTEGER PRIMARY KEY,search TEXT NOT NULL UNIQUE);
CREATE TABLE objects(slug TEXT NOT NULL,seq INTEGER NOT NULL,cx INTEGER NOT NULL,cz INTEGER NOT NULL,uuid TEXT NOT NULL,id TEXT NOT NULL,doc INTEGER NOT NULL,metadata TEXT NOT NULL,PRIMARY KEY(slug,seq));
CREATE INDEX objects_uuid ON objects(slug,uuid);
CREATE INDEX objects_chunk ON objects(slug,cx,cz);
CREATE INDEX objects_document ON objects(slug,doc);
